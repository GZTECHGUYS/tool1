#!/usr/bin/env python3
"""Build an index of the payload knowledge base.

Walks the payload tree, records size/line counts per file, groups them by
category and source, and writes INDEX.tsv + INDEX.md at the repo root.

Usage: python3 index_payloads.py [ROOT]
"""
import os
import sys
from collections import defaultdict

SKIP_DIRS = {".git", "__pycache__", "node_modules"}
SKIP_EXT = {".png", ".jpg", ".jpeg", ".gif", ".ico", ".pdf", ".zip",
            ".gz", ".7z", ".rar", ".exe", ".bin", ".pyc", ".woff", ".woff2"}

# Category keywords used to tag a path for later retrieval.
CATEGORY_RULES = [
    ("xss", ("xss", "cross-site", "html-injection", "svg", "dom")),
    ("sqli", ("sql", "sqli", "injection-sql", "libinjection")),
    ("cmdi", ("commandinjection", "command-injection", "cmd", "rce", "shellshock")),
    ("path-traversal", ("traversal", "dotdotpwn", "lfi", "rfi", "..%2f")),
    ("ssti", ("ssti", "template", "twig", "jinja", "freemarker", "ognl", "spel")),
    ("xxe", ("xxe", "xml", "xpath")),
    ("ssrf", ("ssrf",)),
    ("open-redirect", ("open-redirect", "redirect")),
    ("crlf", ("crlf", "header-injection", "response-splitting")),
    ("auth-passwords", ("password", "passlist", "credential", "default-password",
                        "scadapass", "auth")),
    ("directories", ("dir", "directory", "dirbuster", "dirsearch", "robotsdisallowed",
                     "content-bruteforcing", "vhost", "subdomain", "discovery")),
    ("fuzzing", ("fuzz", "fuzzdb", "wfuzz", "jbrofuzz", "naughty", "intruder", "burp")),
    ("dos", ("dos", "hashcollision", "hashdos", "asphashdos")),
    ("cve-exploit", ("cve", "exploit", "web-cve", "vuln")),
    ("ctf", ("ctf", "maccdc", "defcon", "ists")),
    ("misc", ("misc", "other", "owasp")),
]


def categorize(relpath: str) -> str:
    p = relpath.lower()
    for name, keys in CATEGORY_RULES:
        if any(k in p for k in keys):
            return name
    return "uncategorized"


def count_lines(path: str) -> int:
    total = 0
    try:
        with open(path, "rb") as fh:
            for chunk in iter(lambda: fh.read(1 << 20), b""):
                total += chunk.count(b"\n")
    except (OSError, PermissionError):
        return -1
    return total


def human(n: int) -> str:
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1024 or unit == "GB":
            return f"{n:.1f}{unit}" if unit != "B" else f"{n}B"
        n /= 1024
    return f"{n}"


def main() -> None:
    root = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else
                           os.path.join(os.path.dirname(os.path.abspath(__file__))))
    rows = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
        for fn in filenames:
            ext = os.path.splitext(fn)[1].lower()
            if ext in SKIP_EXT:
                continue
            full = os.path.join(dirpath, fn)
            rel = os.path.relpath(full, root)
            try:
                size = os.path.getsize(full)
            except OSError:
                continue
            # Source = first path component (the upstream repo/collection name).
            source = rel.split(os.sep)[0]
            rows.append({
                "path": rel,
                "source": source,
                "category": categorize(rel),
                "bytes": size,
                "lines": count_lines(full),
            })

    rows.sort(key=lambda r: r["path"])

    tsv = os.path.join(root, "INDEX.tsv")
    with open(tsv, "w", encoding="utf-8") as fh:
        fh.write("path\tsource\tcategory\tbytes\tlines\n")
        for r in rows:
            fh.write(f"{r['path']}\t{r['source']}\t{r['category']}\t"
                     f"{r['bytes']}\t{r['lines']}\n")

    by_source = defaultdict(lambda: [0, 0, 0])
    by_cat = defaultdict(lambda: [0, 0, 0])
    for r in rows:
        for bucket, key in ((by_source, r["source"]), (by_cat, r["category"])):
            bucket[key][0] += 1
            bucket[key][1] += r["bytes"]
            bucket[key][2] += max(r["lines"], 0)

    total_lines = sum(max(r["lines"], 0) for r in rows)
    total_bytes = sum(r["bytes"] for r in rows)

    md = os.path.join(root, "INDEX.md")
    with open(md, "w", encoding="utf-8") as fh:
        fh.write("# Payload Knowledge Base Index\n\n")
        fh.write(f"- Files: **{len(rows)}**\n")
        fh.write(f"- Total size: **{human(total_bytes)}**\n")
        fh.write(f"- Total lines: **{total_lines:,}**\n")
        fh.write(f"- Generated by `index_payloads.py`\n")

        fh.write("\n## By source\n\n| Source | Files | Size | Lines |\n"
                 "|---|---:|---:|---:|\n")
        for key in sorted(by_source):
            n, b, l = by_source[key]
            fh.write(f"| {key} | {n} | {human(b)} | {l:,} |\n")

        fh.write("\n## By category\n\n| Category | Files | Size | Lines |\n"
                 "|---|---:|---:|---:|\n")
        for key in sorted(by_cat):
            n, b, l = by_cat[key]
            fh.write(f"| {key} | {n} | {human(b)} | {l:,} |\n")

        fh.write("\n## Files\n\n| Path | Category | Size | Lines |\n"
                 "|---|---|---:|---:|\n")
        for r in rows:
            lines = f"{r['lines']:,}" if r["lines"] >= 0 else "-"
            fh.write(f"| {r['path']} | {r['category']} | "
                     f"{human(r['bytes'])} | {lines} |\n")

    print(f"indexed {len(rows)} files -> {tsv} and {md}")


if __name__ == "__main__":
    main()
